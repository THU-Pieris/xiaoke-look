# -*- coding: utf-8 -*-
"""Wrap traced paths into the backdrop SVG and write it as a TS module.

usage: build_scene.py <paths.json> <out_scene.ts> [<preview_wide.svg>]

Layout: the picture is pinned to the top right and fitted to the window height
(xMaxYMin meet). The rest of the window is bare paper. The picture fades into
that paper towards the left and the bottom through two gradient masks, and a
few petals drift down very slowly in the blank part.
"""
import json, sys

d = json.load(open(sys.argv[1]))
W, H, paper = d["w"], d["h"], d["paper"]

body = "".join(f'<path fill="{f}" d="{p}"/>' for f, p in d["paths"])

# petals: resting place in markup, slow drift in CSS
petals = [
    # x, y, rot, scale, duration s, delay s
    (-260, 520, 20, 1.0, 46, 0),
    (180, 1500, -35, 0.8, 58, -20),
    (-620, 980, 60, 0.9, 52, -35),
    (520, 1900, 10, 0.7, 64, -12),
]
petal_shape = "M0 0c14-10 34-8 44 4c-12 12-32 12-44-4z"
pg = []
for i, (x, y, r, s, dur, delay) in enumerate(petals):
    pg.append(f'<g transform="translate({x} {y}) rotate({r}) scale({s * 1.4})"><g class="p p{i}">'
              f'<path fill="#ef7e42" d="{petal_shape}"/><path fill="#ac4c27" d="M4 2c12 2 26 2 36 2c-12 4-26 2-36-2z"/></g></g>')
style_rules = [".p{animation:drift 50s linear infinite;opacity:.85}",
               "@keyframes drift{0%{transform:translate(0,-160px) rotate(0deg);opacity:0}"
               "12%{opacity:.85}80%{opacity:.85}100%{transform:translate(-220px,520px) rotate(200deg);opacity:0}}"]
for i, (x, y, r, s, dur, delay) in enumerate(petals):
    style_rules.append(f".p{i}{{animation-duration:{dur}s;animation-delay:{delay}s}}")
style_rules.append("@media (prefers-reduced-motion: reduce){.p{animation:none;opacity:.85}}")
style = "".join(style_rules)

svg = (
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMaxYMin meet">'
    f"<style>{style}</style>"
    "<defs>"
    # left fade: transparent at the left edge, solid from 42 percent of the width
    f'<linearGradient id="fx" x1="0" y1="0" x2="1" y2="0">'
    '<stop offset="0" stop-color="#000"/><stop offset=".1" stop-color="#000"/>'
    '<stop offset=".26" stop-color="#555"/><stop offset=".42" stop-color="#fff"/></linearGradient>'
    # bottom fade: solid to 58 percent, gone by 96 percent
    f'<linearGradient id="fy" x1="0" y1="0" x2="0" y2="1">'
    '<stop offset=".58" stop-color="#fff"/><stop offset=".78" stop-color="#777"/><stop offset=".96" stop-color="#000"/></linearGradient>'
    f'<mask id="mx" maskUnits="userSpaceOnUse" x="0" y="0" width="{W}" height="{H}"><rect width="{W}" height="{H}" fill="url(#fx)"/></mask>'
    f'<mask id="my" maskUnits="userSpaceOnUse" x="0" y="0" width="{W}" height="{H}"><rect width="{W}" height="{H}" fill="url(#fy)"/></mask>'
    "</defs>"
    f'<rect x="-20000" y="-2000" width="40000" height="{H + 40000}" fill="{paper}"/>'
    f'<g mask="url(#mx)"><g mask="url(#my)">{body}</g></g>'
    f'<g>{"".join(pg)}</g>'
    "</svg>"
)
assert "\\" not in svg and "&" not in svg and "<!" not in svg
print("svg chars", len(svg), "limit 131072", "OK" if len(svg) <= 131072 else "TOO BIG")
open(sys.argv[2], "w", encoding="utf8").write(
    "// Generated by tools/build_scene.py from the traced illustration. Do not edit by hand.\n"
    f"export const PAPER = {json.dumps(paper)}\n"
    f"export const SCENE = {json.dumps(svg)}\n"
)
if len(sys.argv) > 3:
    # a wide-window preview: 16:10 box with the scene as the root
    wide = svg.replace(f'viewBox="0 0 {W} {H}"', f'viewBox="0 0 {W} {H}" width="1600" height="1000"', 1)
    open(sys.argv[3], "w", encoding="utf8").write(wide)
